#!/usr/bin/env python3
"""Generate the Tacto app icon, its macOS .icns and the settings menu template.

The SVGs are written from the constants below, so the vector source and the
raster icon cannot drift apart. Rasterizing uses AppKit's own SVG renderer
(through a small Swift program) and iconutil; nothing is downloaded.

    python3 setup/build_brand_assets.py              # write SVGs + .icns
    python3 setup/build_brand_assets.py --check      # tracked SVGs are current (no rendering)
    python3 setup/build_brand_assets.py --preview-dir DIR   # also write review sheets
"""
import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "docs" / "assets"

INK, CORAL, IVORY = "#1b211c", "#fa6b3b", "#f6f4ed"

# The mark from docs/assets/tacto-logo.svg, on its 32-unit grid.
MARK_PATH = "M15.5 3.5V19.5A6 6 0 0 0 21.5 25.5H22.5M26.5 21.5V15A4 4 0 0 0 22.5 11H8.6"
DOT = (5.4, 11)
MARK_CENTER = (15.35, 14.5)  # centre of the stroked mark's bounds

# macOS icon grid: 1024 canvas, 824 body inset 100, continuous-corner radius.
CANVAS, BODY, INSET, RADIUS = 1024, 824, 100, 185.4

# Large sizes use the logo's own weight; 16/32 px get the favicon's heavier
# optical size so the stroke stays at least ~1.5 px and the gap stays open.
OPTICAL = {
    "regular": {"scale": 20.0, "stroke": 3.4, "dot": 2.9, "path": MARK_PATH},
    # The heavier stroke would nearly close the return gap, so the two open
    # ends are pulled back by 1 and 0.5 units; the open gap is the mark.
    "small": {"scale": 23.0, "stroke": 4.4, "dot": 3.3,
              "path": "M15.5 3.5V19.5A6 6 0 0 0 21.5 25.5H22M26.5 20.5V15A4 4 0 0 0 22.5 11H8.6"},
}

VARIANTS = {
    # tile, stroke, dot, edge hairline (or None)
    "ink": (INK, IVORY, CORAL, "#f6f4ed"),
    "ivory": (IVORY, INK, CORAL, "#1b211c"),
    "coral": (CORAL, INK, IVORY, None),
}
CHOSEN = "ink"

ICONSET = [  # (filename, pixels, optical size)
    ("icon_16x16.png", 16, "small"), ("icon_16x16@2x.png", 32, "small"),
    ("icon_32x32.png", 32, "small"), ("icon_32x32@2x.png", 64, "regular"),
    ("icon_128x128.png", 128, "regular"), ("icon_128x128@2x.png", 256, "regular"),
    ("icon_256x256.png", 256, "regular"), ("icon_256x256@2x.png", 512, "regular"),
    ("icon_512x512.png", 512, "regular"), ("icon_512x512@2x.png", 1024, "regular"),
]


def icon_svg(variant=CHOSEN, optical="regular"):
    tile, stroke, dot, edge = VARIANTS[variant]
    o = OPTICAL[optical]
    tx = CANVAS / 2 - MARK_CENTER[0] * o["scale"]
    ty = CANVAS / 2 - MARK_CENTER[1] * o["scale"]
    edge_rect = "" if edge is None else (
        f'\n  <rect x="{INSET + 1}" y="{INSET + 1}" width="{BODY - 2}" height="{BODY - 2}" '
        f'rx="{RADIUS - 1}" fill="none" stroke="{edge}" stroke-opacity="0.2" stroke-width="3"/>')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}" role="img" aria-labelledby="tacto-app-icon-title">
  <title id="tacto-app-icon-title">Tacto</title>
  <!-- Generated by setup/build_brand_assets.py ({variant}, {optical}). Edit the script, not this file.
       macOS grid: {BODY} px body inset {INSET} px; the mark is tacto-logo.svg (small: open ends pulled back for the heavier stroke). -->
  <rect x="{INSET}" y="{INSET}" width="{BODY}" height="{BODY}" rx="{RADIUS}" fill="{tile}"/>{edge_rect}
  <g transform="translate({tx:.2f} {ty:.2f}) scale({o["scale"]})">
    <path d="{o["path"]}" fill="none" stroke="{stroke}" stroke-width="{o["stroke"]}" stroke-linecap="round" stroke-linejoin="round"/>
    <circle cx="{DOT[0]}" cy="{DOT[1]}" r="{o["dot"]}" fill="{dot}"/>
  </g>
</svg>
'''


def menu_template_svg():
    # Settings, not activity: two slider tracks with hollow knobs. No filled
    # dot, so it cannot be read as the task indicator "● Tacto".
    return '''<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 18 18" role="img" aria-labelledby="tacto-menu-title">
  <title id="tacto-menu-title">Tacto 설정</title>
  <!-- Generated by setup/build_brand_assets.py. Template image: black + alpha only;
       set NSImage.isTemplate = true so macOS tints it for light, dark and highlighted menus.
       Round caps and the hollow knobs echo the mark's monoline stroke. -->
  <g fill="none" stroke="#000" stroke-width="1.6" stroke-linecap="round">
    <path d="M2.5 5.5H9M14.5 5.5H15.5"/>
    <circle cx="11.75" cy="5.5" r="2.25"/>
    <path d="M2.5 12.5H3.5M9 12.5H15.5"/>
    <circle cx="6.25" cy="12.5" r="2.25"/>
  </g>
</svg>
'''


TRACKED = {
    "tacto-app-icon.svg": lambda: icon_svg(CHOSEN, "regular"),
    "tacto-app-icon-small.svg": lambda: icon_svg(CHOSEN, "small"),
    "tacto-menu-template.svg": menu_template_svg,
}

# Rasterizes SVG with AppKit and composes review sheets. Arguments:
#   render <svg> <png> <pixels>
#   sheet <png-out> <width> <height> <bg-hex> then repeated <png> <x> <y> <size> <nearest 0|1>
SWIFT = r'''
import AppKit
func color(_ hex: String) -> NSColor {
    var v: UInt64 = 0; Scanner(string: String(hex.dropFirst())).scanHexInt64(&v)
    return NSColor(srgbRed: CGFloat((v >> 16) & 255) / 255, green: CGFloat((v >> 8) & 255) / 255,
                   blue: CGFloat(v & 255) / 255, alpha: 1)
}
func canvas(_ w: Int, _ h: Int) -> NSBitmapImageRep {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h, bitsPerSample: 8,
        samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
        bytesPerRow: 0, bitsPerPixel: 0)!.retagging(with: .sRGB)!
    rep.size = NSSize(width: w, height: h); return rep
}
func save(_ rep: NSBitmapImageRep, _ path: String) {
    try! rep.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: path))
}
let a = CommandLine.arguments
if a[1] == "render" {
    guard let img = NSImage(contentsOf: URL(fileURLWithPath: a[2])) else { fatalError("svg load failed: \(a[2])") }
    let px = Int(a[4])!; let rep = canvas(px, px)
    NSGraphicsContext.saveGraphicsState()
    let ctx = NSGraphicsContext(bitmapImageRep: rep)!; ctx.imageInterpolation = .high
    NSGraphicsContext.current = ctx
    img.draw(in: NSRect(x: 0, y: 0, width: px, height: px), from: .zero, operation: .sourceOver, fraction: 1)
    NSGraphicsContext.restoreGraphicsState(); save(rep, a[3])
} else {
    let w = Int(a[3])!, h = Int(a[4])!; let rep = canvas(w, h)
    NSGraphicsContext.saveGraphicsState()
    let ctx = NSGraphicsContext(bitmapImageRep: rep)!; NSGraphicsContext.current = ctx
    color(a[5]).setFill(); NSRect(x: 0, y: 0, width: w, height: h).fill()
    var i = 6
    while i + 4 < a.count {
        let img = NSImage(contentsOf: URL(fileURLWithPath: a[i]))!
        let x = Double(a[i+1])!, y = Double(a[i+2])!, s = Double(a[i+3])!
        ctx.imageInterpolation = a[i+4] == "1" ? .none : .high
        img.draw(in: NSRect(x: x, y: Double(h) - y - s, width: s, height: s), from: .zero, operation: .sourceOver, fraction: 1)
        i += 5
    }
    NSGraphicsContext.restoreGraphicsState(); save(rep, a[2])
}
'''


class Renderer:
    def __init__(self, work):
        self.work = Path(work)
        source = self.work / "render.swift"
        source.write_text(SWIFT)
        self.binary = self.work / "render"
        subprocess.run(["swiftc", "-O", "-o", str(self.binary), str(source)], check=True)

    def render(self, svg_text, png, pixels):
        svg = self.work / (Path(png).stem + ".svg")
        svg.write_text(svg_text)
        subprocess.run([str(self.binary), "render", str(svg), str(png), str(pixels)], check=True)

    def sheet(self, out, width, height, background, placements):
        args = [str(self.binary), "sheet", str(out), str(width), str(height), background]
        for png, x, y, size, nearest in placements:
            args += [str(png), str(x), str(y), str(size), "1" if nearest else "0"]
        subprocess.run(args, check=True)


def build_icns(renderer, out):
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "Tacto.iconset"
        iconset.mkdir()
        for name, pixels, optical in ICONSET:
            renderer.render(icon_svg(CHOSEN, optical), iconset / name, pixels)
        subprocess.run(["iconutil", "-c", "icns", "-o", str(out), str(iconset)], check=True)


def _luminance(hex_color):
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a, b):
    la, lb = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def previews(renderer, out_dir):
    """Review sheets for a person deciding; not tracked in the repository."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    pngs = {}
    for variant in VARIANTS:
        for optical, pixels in (("regular", 256), ("small", 32), ("small", 16)):
            path = out / f"{variant}-{optical}-{pixels}.png"
            renderer.render(icon_svg(variant, optical), path, pixels)
            pngs[variant, pixels] = path
    # Contact sheet: each variant at 256 / 32 / 16 on a light and a dark ground.
    for ground, name in (("#ececec", "light"), ("#1e1e1e", "dark")):
        placements = []
        for column, variant in enumerate(VARIANTS):
            x = 24 + column * 296
            placements += [(pngs[variant, 256], x, 24, 256, False),
                           (pngs[variant, 32], x + 40, 300, 32, False),
                           (pngs[variant, 16], x + 96, 308, 16, False),
                           (pngs[variant, 16], x + 136, 290, 64, True)]
        renderer.sheet(out / f"contact-sheet-{name}.png", 24 + 296 * len(VARIANTS), 380, ground, placements)
    # The chosen icon at 16/32/128/512, as shipped in the iconset, 1:1 plus 8x pixel views.
    chosen = {}
    for pixels, optical in ((16, "small"), (32, "small"), (128, "regular"), (512, "regular")):
        path = out / f"chosen-{pixels}.png"
        renderer.render(icon_svg(CHOSEN, optical), path, pixels)
        chosen[pixels] = path
    for ground, name in (("#ffffff", "light"), ("#1e1e1e", "dark")):
        renderer.sheet(out / f"chosen-sizes-{name}.png", 1000, 560, ground, [
            (chosen[512], 24, 24, 512, False), (chosen[128], 560, 24, 128, False),
            (chosen[32], 712, 24, 32, False), (chosen[16], 768, 24, 16, False),
            (chosen[32], 560, 200, 256, True), (chosen[16], 840, 200, 128, True)])
    template = out / "menu-template-36.png"
    renderer.render(menu_template_svg(), template, 36)
    lines = ["pair,ratio"]
    for label, a, b in (("ivory stroke on ink tile", IVORY, INK), ("coral dot on ink tile", CORAL, INK),
                        ("ink stroke on ivory tile", INK, IVORY), ("coral dot on ivory tile", CORAL, IVORY),
                        ("ink stroke on coral tile", INK, CORAL), ("ivory dot on coral tile", IVORY, CORAL),
                        ("ink tile on dark Dock #1e1e1e", INK, "#1e1e1e"),
                        ("ink tile on light window #ececec", INK, "#ececec"),
                        ("ivory tile on light window #ececec", IVORY, "#ececec"),
                        ("ivory tile on dark Dock #1e1e1e", IVORY, "#1e1e1e")):
        lines.append(f"{label},{contrast(a, b):.2f}")
    (out / "contrast.csv").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if tracked SVGs differ from the generator")
    parser.add_argument("--preview-dir", help="also write contact sheets and size previews here")
    args = parser.parse_args()

    stale = [name for name, make in TRACKED.items()
             if not (ASSETS / name).is_file() or (ASSETS / name).read_text() != make()]
    if args.check:
        if stale:
            print("stale brand assets: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    if sys.platform != "darwin" or not shutil.which("iconutil") or not shutil.which("swiftc"):
        print("macOS with swiftc and iconutil is required to render the icon", file=sys.stderr)
        return 2
    for name, make in TRACKED.items():
        (ASSETS / name).write_text(make())
    with tempfile.TemporaryDirectory() as work:
        renderer = Renderer(work)
        build_icns(renderer, ASSETS / "tacto-app.icns")
        if args.preview_dir:
            previews(renderer, os.path.abspath(args.preview_dir))
    print("wrote " + ", ".join(sorted([*TRACKED, "tacto-app.icns"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
