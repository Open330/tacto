"""Observable model-call metadata, without inventing provider telemetry.

request_id is generated by Tacto for correlation, never a provider receipt.
A stopped local CLI does not prove that its remote generation was cancelled.
"""
from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field
from typing import Literal


@dataclass(frozen=True)
class ProviderError:
    code: str
    message: str


@dataclass(frozen=True)
class ProviderAttempt:
    """One local route invocation; no prompt, answer, or raw error output."""
    provider: str
    transport: str
    status: Literal['ok', 'error', 'timeout', 'no_answer', 'invalid_response']
    elapsed_seconds: float
    error_code: str | None = None
    model: str | None = None
    provider_request_id: str | None = None
    provider_thread_id: str | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None
    cached_input_tokens: int | None = None
    cache_creation_input_tokens: int | None = None
    total_input_tokens: int | None = None
    input_tokens_basis: str | None = None
    cost: float | None = None
    cost_currency: str | None = None
    cost_basis: str | None = None


@dataclass(frozen=True)
class ProviderResult:
    request_id: str
    requested_provider: str
    provider: str | None
    transport: str | None
    status: Literal["ok", "error", "timeout"]
    text: str | None
    error: ProviderError | None
    elapsed_seconds: float
    model: str | None = None
    provider_request_id: str | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None
    cost: float | None = None
    cost_currency: str | None = None
    cancellation_supported: bool = False
    provider_thread_id: str | None = None
    cached_input_tokens: int | None = None
    cost_basis: str | None = None
    input_tokens_basis: str | None = None
    cache_creation_input_tokens: int | None = None
    total_input_tokens: int | None = None
    attempts: tuple[ProviderAttempt, ...] = field(default_factory=tuple)

    def to_dict(self) -> dict:
        """JSON-compatible envelope; absent telemetry stays null, not zero."""
        result = asdict(self)
        result['attempts'] = [asdict(attempt) for attempt in self.attempts]
        return result


def finite_nonnegative_number(value):
    """Finite, float-compatible telemetry; never coerce strings or booleans."""
    import math
    if type(value) not in (int,float) or value<0:return False
    try:return math.isfinite(value)
    except OverflowError:return False


def parse_provider_result(value: dict) -> ProviderResult:
    """Validate a version-1 transport envelope; never coerce telemetry values."""
    from dataclasses import fields
    if type(value) is not dict or set(value) - {f.name for f in fields(ProviderResult)}:
        raise ValueError('invalid provider result fields')
    data = dict(value)
    attempts = data.pop('attempts', [])
    if type(attempts) is not list:
        raise ValueError('invalid provider attempts')
    parsed_attempts = []
    for attempt in attempts:
        allowed = {f.name for f in fields(ProviderAttempt)}
        if type(attempt) is not dict or set(attempt) - allowed:
            raise ValueError('invalid provider attempt fields')
        if any(type(attempt.get(name)) is not str or not attempt[name]
               for name in ('provider', 'transport')):
            raise ValueError('missing provider attempt route')
        attempt_status = attempt.get('status')
        if attempt_status not in ('ok', 'error', 'timeout', 'no_answer', 'invalid_response'):
            raise ValueError('invalid provider attempt status')
        import re
        code = attempt.get('error_code')
        if code is not None and (type(code) is not str or not re.fullmatch(r'[A-Za-z_]{1,40}', code)):
            raise ValueError('invalid provider attempt code')
        if attempt_status == 'ok' and code is not None:
            raise ValueError('successful provider attempt with error')
        # Reuse the envelope's strict telemetry checks, excluding text entirely.
        telemetry = {k: v for k, v in attempt.items() if k not in ('status', 'error_code')}
        parse_provider_result(dict(telemetry, request_id='attempt', requested_provider=attempt.get('provider'),
            status='ok' if attempt_status == 'ok' else 'error',
            text='observed' if attempt_status == 'ok' else None,
            error=None if attempt_status == 'ok' else {'code': code or 'NoAnswer', 'message': 'Attempt failed'}))
        try:
            parsed_attempts.append(ProviderAttempt(**attempt))
        except TypeError as exc:
            raise ValueError('incomplete provider attempt') from exc
    data['attempts'] = tuple(parsed_attempts)
    for name in ('request_id', 'requested_provider', 'status'):
        if type(data.get(name)) is not str or not data[name]:
            raise ValueError('missing provider identity/status')
    if data['status'] not in ('ok', 'error', 'timeout'):
        raise ValueError('invalid provider status')
    for name in ('provider', 'transport', 'model', 'provider_request_id',
                 'provider_thread_id', 'cost_currency', 'cost_basis', 'input_tokens_basis'):
        if data.get(name) is not None and (type(data[name]) is not str or not data[name]):
            raise ValueError('invalid provider metadata string')
    for name in ('input_tokens', 'output_tokens', 'cached_input_tokens',
                 'cache_creation_input_tokens', 'total_input_tokens'):
        if data.get(name) is not None and (type(data[name]) is not int or data[name] < 0):
            raise ValueError('invalid provider token count')
    basis = data.get('input_tokens_basis')
    if basis not in (None, 'uncached', 'total'):
        raise ValueError('invalid input token basis')
    # For total-basis telemetry, cache reads are included in input_tokens.
    # Apply the same consistency rule as the Codex CLI parser to shared
    # envelopes and nested attempts; unknown/uncached bases are distinct.
    input_count, cached_count = data.get('input_tokens'), data.get('cached_input_tokens')
    if basis == 'total' and input_count is not None and cached_count is not None and cached_count > input_count:
        raise ValueError('cached input exceeds total input tokens')
    total = data.get('total_input_tokens')
    if total is not None:
        if basis == 'total' and total != data.get('input_tokens'):
            raise ValueError('inconsistent total input tokens')
        if basis == 'uncached':
            parts = [data.get(k) for k in ('input_tokens', 'cached_input_tokens', 'cache_creation_input_tokens')]
            if any(v is None for v in parts) or total != sum(parts):
                raise ValueError('incomplete or inconsistent input token sum')
    for name in ('elapsed_seconds', 'cost'):
        number = data.get(name)
        if number is None and name == 'cost':
            continue
        if not finite_nonnegative_number(number):
            raise ValueError('invalid provider timing/cost')
    if 'cancellation_supported' in data and type(data['cancellation_supported']) is not bool:
        raise ValueError('invalid cancellation support')
    error = data.get('error')
    if data['status'] == 'ok':
        if type(data.get('text')) is not str or not data['text'] or error is not None:
            raise ValueError('invalid successful provider result')
    else:
        if data.get('text') is not None or type(error) is not dict or set(error) != {'code', 'message'}:
            raise ValueError('invalid failed provider result')
        if any(type(error[k]) is not str or not error[k] for k in error):
            raise ValueError('invalid provider error')
        data['error'] = ProviderError(**error)
    try:
        return ProviderResult(**data)
    except TypeError as exc:
        raise ValueError('incomplete provider result') from exc


class ProviderUnavailable(RuntimeError):
    """A provider that answered, but with a reason it cannot serve this request.

    Carries a code from a closed set and nothing else. Provider output can hold
    prompt text, account details or paths, so none of it is kept — only which
    of these known states it was. "Model request failed" used to cover all of
    them, including "not logged in" and "usage limit reached", which are the
    two a person can fix and the one message that told them nothing.
    """
    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


UNAVAILABLE_REASONS = frozenset({'not_logged_in', 'usage_limit', 'organization_access_disabled', 'unsupported_client', 'authentication_failed'})


_UNAVAILABLE = (
    ("not_logged_in", ("please run /login", "not logged in")),
    ("usage_limit", ("usage limit", "rate limit", "quota")),
)


def classify_unavailable(*outputs, provider=None) -> str | None:
    """Map provider output to a reason code, or None if it is not a known one."""
    if provider == 'opencode':
        for output in outputs:
            if not isinstance(output,str) or len(output)>1024*1024:continue
            for line in output.splitlines():
                if line.strip()=='Error: Token refresh failed: 401':
                    return 'authentication_failed'
                try:frame=json.loads(line)
                except (ValueError,TypeError,RecursionError):continue
                if (type(frame) is dict and frame.get('type')=='error'
                        and type(frame.get('timestamp')) is int and frame['timestamp']>=0
                        and isinstance(frame.get('sessionID'),str)
                        and re.fullmatch(r'ses_[A-Za-z0-9_-]{1,252}',frame['sessionID']) is not None and type(frame.get('error')) is dict
                        and frame['error'].get('name')=='UnknownError'
                        and type(frame['error'].get('data')) is dict
                        and frame['error']['data'].get('message')=='Error: Token refresh failed: 401'):
                    return 'authentication_failed'
    text = " ".join(o for o in outputs if isinstance(o, str)).lower()
    # Observed Gemini authentication refusal; neither a model mention of a
    # client nor a bare status token alone establishes this condition.
    if (provider == 'gemini' and 'error authenticating: ineligibletiererror:' in text
            and 'unsupported_client' in text):
        return 'unsupported_client'
    for code, needles in _UNAVAILABLE:
        if any(n in text for n in needles):
            return code
    return None
